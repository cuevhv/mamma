#!/usr/bin/env python
"""Measure wall-time, peak GPU memory, and peak CPU RSS of a subprocess.

A small, reusable harness for quantifying optimization PRs (see
``docs/optimization-roadmap.md``). It runs an arbitrary command (typically a
single pipeline step), samples peak GPU memory (per-process, via
``nvidia-smi``) and peak CPU RSS (the process tree, via ``psutil``), and times
the whole run. Each invocation appends one JSON line to
``docs/benchmarks/results.jsonl`` and regenerates ``docs/benchmarks/README.md``
so improvements are tracked over time and comparable across commits.

Usage::

    python scripts/benchmark.py --label "ma_2d baseline bs1 (426f)" \
        --meta '{"step":"ma_2d","frames":426,"batch_size":1}' \
        --cwd landmarks -- python run_ma_2d.py <args...>

Run the same label a few times and compare the medians; the first run on a
cold machine pays one-time load/cache costs (see observation F2).
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import threading
import time
from pathlib import Path

import psutil

_REPO = Path(__file__).resolve().parents[1]
_RESULTS = _REPO / "docs" / "benchmarks" / "results.jsonl"
_HAS_NVSMI = shutil.which("nvidia-smi") is not None


def _git_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=_REPO
        ).decode().strip()
    except Exception:
        return "unknown"


def _tree_pids(proc: subprocess.Popen) -> set:
    try:
        p = psutil.Process(proc.pid)
        return {p.pid} | {c.pid for c in p.children(recursive=True)}
    except psutil.Error:
        return {proc.pid}


def _rss_mb(pids: set) -> float:
    total = 0
    for pid in pids:
        try:
            total += psutil.Process(pid).memory_info().rss
        except psutil.Error:
            pass
    return total / 1e6


def _gpu_mb(pids: set):
    """Summed GPU memory (MB) used by our process tree, or None if unavailable."""
    if not _HAS_NVSMI:
        return None
    try:
        out = subprocess.check_output(
            ["nvidia-smi", "--query-compute-apps=pid,used_memory",
             "--format=csv,noheader,nounits"],
            stderr=subprocess.DEVNULL,
        ).decode()
    except Exception:
        return None
    total = 0
    for line in out.strip().splitlines():
        if not line.strip():
            continue
        pid_s, mem_s = (x.strip() for x in line.split(","))
        if int(pid_s) in pids:
            total += int(mem_s)
    return total


class _Sampler(threading.Thread):
    def __init__(self, proc: subprocess.Popen, interval: float = 0.2):
        super().__init__(daemon=True)
        self.proc = proc
        self.interval = interval
        self.peak_gpu_mb = 0
        self.peak_rss_mb = 0.0
        self._gpu_seen = False
        self._stop = False

    def run(self) -> None:
        while not self._stop and self.proc.poll() is None:
            pids = _tree_pids(self.proc)
            g = _gpu_mb(pids)
            if g is not None:
                self._gpu_seen = True
                self.peak_gpu_mb = max(self.peak_gpu_mb, g)
            self.peak_rss_mb = max(self.peak_rss_mb, _rss_mb(pids))
            time.sleep(self.interval)

    def stop(self) -> None:
        self._stop = True


def _render_table() -> None:
    rows = [json.loads(l) for l in _RESULTS.read_text().splitlines() if l.strip()]
    lines = [
        "# Benchmark results",
        "",
        "Generated by `scripts/benchmark.py`; one row per run. GPU/CPU figures",
        "are peak usage of the measured process tree. Compare medians of repeated",
        "rows, and only within the same machine and warm/cold state.",
        "",
        "| label | commit | wall (s) | peak GPU (MB) | peak CPU RSS (MB) | rc |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for r in rows:
        gpu = r["peak_gpu_mb"] if r["peak_gpu_mb"] is not None else "n/a"
        lines.append(
            f"| {r['label']} | {r['commit']} | {r['wall_s']} | {gpu} | "
            f"{r['peak_cpu_rss_mb']} | {r['returncode']} |"
        )
    (_RESULTS.parent / "README.md").write_text("\n".join(lines) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(prog="python scripts/benchmark.py")
    ap.add_argument("--label", required=True, help="Human-readable run label.")
    ap.add_argument("--meta", default=None, help="JSON string of extra metadata to store.")
    ap.add_argument("--cwd", default=None, help="Working directory for the command.")
    ap.add_argument("--interval", type=float, default=0.2, help="Sampling interval (s).")
    ap.add_argument("cmd", nargs=argparse.REMAINDER,
                    help="-- followed by the command to run.")
    args = ap.parse_args()
    cmd = args.cmd[1:] if args.cmd and args.cmd[0] == "--" else args.cmd
    if not cmd:
        ap.error("provide a command after `--`")

    cwd = str((_REPO / args.cwd).resolve()) if args.cwd else str(_REPO)
    t0 = time.perf_counter()
    proc = subprocess.Popen(cmd, cwd=cwd)
    sampler = _Sampler(proc, interval=args.interval)
    sampler.start()
    proc.wait()
    sampler.stop()
    sampler.join(timeout=2)
    wall_s = time.perf_counter() - t0

    rec = {
        "label": args.label,
        "commit": _git_commit(),
        "returncode": proc.returncode,
        "wall_s": round(wall_s, 2),
        "peak_gpu_mb": sampler.peak_gpu_mb if sampler._gpu_seen else None,
        "peak_cpu_rss_mb": round(sampler.peak_rss_mb),
        "cmd": cmd,
    }
    if args.meta:
        rec["meta"] = json.loads(args.meta)
    _RESULTS.parent.mkdir(parents=True, exist_ok=True)
    with open(_RESULTS, "a") as f:
        f.write(json.dumps(rec) + "\n")
    _render_table()

    gpu = rec["peak_gpu_mb"]
    print(f"{args.label}: {wall_s:.2f}s  "
          f"gpu_peak={gpu if gpu is not None else 'n/a'}MB  "
          f"cpu_rss_peak={rec['peak_cpu_rss_mb']}MB  rc={proc.returncode}")
    return proc.returncode


if __name__ == "__main__":
    raise SystemExit(main())
